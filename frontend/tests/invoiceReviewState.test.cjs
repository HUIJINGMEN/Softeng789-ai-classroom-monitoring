const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const vm = require('node:vm');
const { buildSync } = require('esbuild');

const code = buildSync({
  entryPoints: [path.join(__dirname, '../src/features/payments/useInvoiceReview.ts')],
  bundle: true, write: false, platform: 'node', format: 'cjs',
  external: ['react', './api', '../../lib/apiClient', '../../lib/saveDownload']
}).outputFiles[0].text;

function harness() {
  const values = [], effects = [], queued = [], calls = [], confirmations = [];
  let cursor = 0, id = 0;
  const react = {
    useState(initial) {
      const i = cursor++;
      if (!(i in values)) values[i] = typeof initial === 'function' ? initial() : initial;
      return [values[i], next => { values[i] = typeof next === 'function' ? next(values[i]) : next; }];
    },
    useMemo(fn, deps) {
      const i = cursor++;
      if (!values[i] || deps.some((value, n) => !Object.is(value, values[i].deps[n]))) values[i] = { deps, value: fn() };
      return values[i].value;
    },
    useEffect(fn, deps) {
      const i = cursor++, old = effects[i];
      if (!old || deps.some((value, n) => !Object.is(value, old.deps[n]))) queued.push(() => {
        old?.cleanup?.(); effects[i] = { deps, cleanup: fn() };
      });
    }
  };
  const api = new Proxy({}, { get: (_, name) => (...args) => new Promise((resolve, reject) => {
    calls.push({ name, args, resolve, reject });
  }) });
  const browser = { discard: false, confirm(message) { confirmations.push(message); return browser.discard; } };
  const module = { exports: {} };
  vm.runInNewContext(code, { module, exports: module.exports, window: browser,
    crypto: { randomUUID: () => `key-${++id}` }, require(name) {
      if (name === 'react') return react;
      if (name === './api') return api;
      if (name === '../../lib/apiClient') return { apiMessage: cause => cause.message };
      if (name === '../../lib/saveDownload') return { saveDownload() {} };
      throw new Error(`Unexpected dependency: ${name}`);
    } });
  const props = { invoiceId: 'invoice-1', studentName: 'Audit student', onClose() {}, onUpdated() {} };
  return {
    calls, props, browser, confirmations,
    render() {
      cursor = 0;
      const model = module.exports.useInvoiceReview(props);
      queued.splice(0).forEach(fn => fn());
      return model;
    },
    unmount() { effects.forEach(effect => effect?.cleanup?.()); },
    remount() { this.unmount(); values.length = effects.length = queued.length = 0; },
    snapshot() { return JSON.stringify(values); }
  };
}

const flush = async () => { for (let i = 0; i < 8; i++) await Promise.resolve(); };
const account = (overrides = {}) => ({ invoice: { id: 'invoice-1', status: 'DRAFT', note: 'Creation note',
  balance: 50, payments: 50, currency: 'NZD', coursePurchases: [], sessionPackage: null,
  messageReviewedAt: null, messageDraftSavedAt: null, lastEmailedAt: null, ...overrides }, transferOptions: [] });

async function loadDraft(h) {
  h.render(); h.calls[0].resolve(account()); await flush();
  assert.equal(h.calls[1].name, 'generateInvoiceMessage');
  h.calls[1].resolve({ message: 'AI draft', provider: 'Test provider' }); await flush();
  return h.render();
}

test('automatic generation creates only an editable private draft, never a save or delivery', async () => {
  const h = harness(); const model = await loadDraft(h);
  assert.equal(model.message, 'AI draft');
  assert.equal(model.messageDirty, true);
  assert.equal(model.busy, '');
  assert.equal(model.messageHelp, 'Generated by Test provider · review before sending');
  assert.deepEqual(h.calls.map(call => call.name), ['getInvoiceAccount', 'generateInvoiceMessage']);
  h.unmount();
});

test('editing and reopening use the hook-owned draft cache without a second AI generation', async () => {
  const h = harness(); await loadDraft(h);
  h.render().editMessage('Edited wording');
  h.remount(); h.render();
  h.calls[2].resolve(account()); await flush();
  assert.equal(h.render().message, 'Edited wording');
  assert.equal(h.render().messageDirty, true);
  assert.equal(h.calls.filter(call => call.name === 'generateInvoiceMessage').length, 1);
  h.unmount();
});

test('reviewed messages skip AI; failed AI leaves fallback editable and supports explicit retry', async () => {
  const reviewed = harness(); reviewed.render();
  reviewed.calls[0].resolve(account({ messageReviewedAt: '2026-10-18T00:00:00Z', note: 'Reviewed message' })); await flush();
  assert.equal(reviewed.render().message, 'Reviewed message');
  assert.equal(reviewed.render().messageDirty, false);
  assert.equal(reviewed.calls.length, 1); reviewed.unmount();

  const h = harness(); h.render(); h.calls[0].resolve(account()); await flush();
  h.calls[1].reject(new Error('AI offline')); await flush();
  assert.equal(h.render().message, 'Creation note');
  assert(h.render().draftError.includes('AI offline'));
  h.render().editMessage('Manual wording');
  const retry = h.render().generateDraft();
  assert.equal(h.render().message, 'Manual wording');
  h.calls[2].resolve({ message: 'New AI draft', provider: 'Test provider' }); await retry;
  assert.equal(h.render().message, 'New AI draft');
  assert.equal(h.render().draftError, ''); h.unmount();
});

test('saving a message explicitly keeps approval false and does not publish or email', async () => {
  const h = harness(); await loadDraft(h);
  h.render().editMessage('  My checked wording  ');
  const saving = h.render().saveMessage();
  assert.equal(h.calls[2].name, 'saveInvoiceMessage');
  assert.deepEqual(Array.from(h.calls[2].args), ['invoice-1', 'My checked wording', false]);
  h.calls[2].resolve({}); await saving;
  assert.equal(h.render().messageDirty, false);
  assert(h.render().notice.includes('still private'));
  assert(!h.calls.some(call => call.name === 'emailInvoice')); h.unmount();
});

test('delivery retries reuse the idempotency key and failures do not discard edits or report success', async () => {
  const h = harness(); let updates = 0; h.props.onUpdated = () => updates++;
  await loadDraft(h);
  const first = h.render().deliver();
  const key = h.calls[2].args[2];
  h.calls[2].reject(new Error('Delivery offline')); await first;
  assert.equal(h.render().messageDirty, true);
  assert.equal(h.render().error, 'Delivery offline');
  assert.equal(updates, 0);
  const retry = h.render().deliver();
  assert.equal(h.calls[3].args[2], key);
  h.calls[3].resolve({ status: 'SENT', message: 'Invoice sent' }); await flush();
  assert.equal(h.calls[4].name, 'getInvoiceAccount');
  h.calls[4].resolve(account({ status: 'PENDING', lastEmailedAt: '2026-10-18T00:00:00Z' })); await retry;
  assert.equal(h.render().messageDirty, false);
  assert.equal(h.render().notice, 'Invoice sent');
  assert.equal(updates, 1); h.unmount();
});

test('late initial loads cannot update an unmounted editor or start an AI request', async () => {
  const h = harness(); h.render(); h.unmount();
  const before = h.snapshot(); h.calls[0].resolve(account()); await flush();
  assert.equal(h.snapshot(), before);
  assert.equal(h.calls.length, 1);
});

test('an uncertain delivery is not success, keeps edits and does not reload or generate a new retry key', async () => {
  const h = harness(); await loadDraft(h);
  const attempt = h.render().deliver(); const key = h.calls[2].args[2];
  h.calls[2].resolve({ status: 'UNKNOWN', message: 'Check delivery before resending.' }); await attempt;
  assert.equal(h.render().messageDirty, true);
  assert.equal(h.render().error, 'Check delivery before resending.');
  assert.equal(h.calls.length, 3);
  const retry = h.render().deliver(); assert.equal(h.calls[3].args[2], key);
  h.calls[3].resolve({ status: 'UNKNOWN', message: 'Check delivery before resending.' }); await retry;
  h.unmount();
});

test('unsaved edits require confirmation before closing', async () => {
  const h = harness(); let closes = 0; h.props.onClose = () => closes++;
  await loadDraft(h); h.render().requestClose(); assert.equal(closes, 0);
  assert.equal(h.confirmations.length, 1);
  h.browser.discard = true; h.render().requestClose(); assert.equal(closes, 1); h.unmount();
});
